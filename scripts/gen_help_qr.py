"""Bake the Parent Menu QR matrices into purplecomputer/qr_data.py.

Dev-time only: the `qrcode` package is NOT a runtime dependency. Purple ships
the pre-computed matrices so the QR screens render them with no import cost.

The in-app screen has room, so this uses the full URL at ECC_H for robustness.
The small print flyer uses a denser, uppercase variant: see
landing/scripts/generate-qr.sh.

Usage:
    just python scripts/gen_help_qr.py
"""

from pathlib import Path

import qrcode
from qrcode.constants import ERROR_CORRECT_H

CODES = {
    "HELP": "https://purplecomputer.org/help",
    "FRIDGE": "https://purplecomputer.org/fridge",
}
OUT = Path(__file__).resolve().parent.parent / "purplecomputer" / "qr_data.py"


def matrix(url: str) -> list[str]:
    qr = qrcode.QRCode(error_correction=ERROR_CORRECT_H, border=2)
    qr.add_data(url)
    qr.make(fit=True)
    return ["".join("1" if cell else "0" for cell in row) for row in qr.get_matrix()]


def main() -> None:
    parts = ['"""Generated by scripts/gen_help_qr.py. Do not edit by hand."""\n']
    for name, url in CODES.items():
        rows = matrix(url)
        body = ",\n".join(f'    "{r}"' for r in rows)
        parts.append(
            f'{name}_QR_URL = "{url}"\n\n'
            "# Each string is one QR module row, including the quiet-zone border.\n"
            f"{name}_QR_MATRIX = [\n{body},\n]\n"
        )
        print(f"{name}: {len(rows)}x{len(rows)} modules for {url}")
    OUT.write_text("\n".join(parts))


if __name__ == "__main__":
    main()
